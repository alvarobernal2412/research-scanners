"""File inventory: decide which files in a project are eligible source."""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

sys.path.insert(0, str(Path(__file__).resolve().parent))

MAX_FILE_BYTES = 1_000_000
MINIFIED_LINE_CHARS = 500
VENDOR_DIRS = frozenset({
    "node_modules", "vendor", "third_party", "bower_components", ".venv", "venv",
    "site-packages", "dist", "build", "target", ".git", "__pycache__",
})
GENERATED_MARKERS = ("@generated", "DO NOT EDIT", "Code generated", "autogenerated")
LANGUAGES = {
    **{e: "c_like" for e in (
        "js", "jsx", "mjs", "ts", "tsx", "java", "c", "h", "cpp", "cc", "hpp", "cs",
        "go", "rs", "kt", "swift", "php", "scala", "dart")},
    **{e: "hash" for e in ("py", "rb", "sh", "r", "pl")},
}

_SENSITIVE_NAME = re.compile(
    r"^(\.env(\..*)?|id_(rsa|dsa|ecdsa|ed25519)(\.pub)?|\.npmrc|\.netrc|credentials(\..*)?)$",
    re.IGNORECASE,
)
_SENSITIVE_EXT = {".pem", ".key", ".p12", ".pfx", ".keystore", ".jks"}
_LICENSE_NAME = re.compile(r"^(licen[sc]e|copying|unlicense|notice)(\.[A-Za-z0-9]+)?$", re.IGNORECASE)
_SUPPORTED_MANIFESTS = {
    "package.json": "package.json",
    "package-lock.json": "package-lock.json",
    "pyproject.toml": "pyproject",
}
_UNSUPPORTED_MANIFESTS = {
    "go.mod", "go.sum", "cargo.toml", "cargo.lock", "pom.xml", "build.gradle",
    "build.gradle.kts", "gemfile", "gemfile.lock", "composer.json", "yarn.lock",
    "pnpm-lock.yaml", "pipfile", "pipfile.lock", "poetry.lock", "pubspec.yaml",
}
_LINE_SPLIT = re.compile(r"\r\n|\n|\r")


class InventoryError(Exception):
    def __init__(self, code: str, message: str = ""):
        super().__init__(message or code)
        self.code = code


@dataclass
class SourceFile:
    rel: str
    path: Path
    lang: str
    size: int


@dataclass
class Skipped:
    rel: str
    reason: str


@dataclass
class Manifest:
    rel: str
    kind: str


@dataclass
class Inventory:
    root: Path
    sources: list[SourceFile] = field(default_factory=list)
    skipped: list[Skipped] = field(default_factory=list)
    manifests: list[Manifest] = field(default_factory=list)
    license_files: list[str] = field(default_factory=list)
    listing: str = "walk"


def read_lines(path: Path) -> list[str]:
    """Lines as an editor numbers them (CRLF, LF and lone CR; BOM dropped)."""
    text = Path(path).read_bytes().decode("utf-8-sig", errors="replace")
    if not text:
        return []
    lines = _LINE_SPLIT.split(text)
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def _git_lists(root: Path) -> tuple[list[str], set[str]] | None:
    if not (root / ".git").exists() or shutil.which("git") is None:
        return None

    def run(*args: str) -> list[str]:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", *args, "-z"],
            capture_output=True, check=True,
        ).stdout
        return [p.decode("utf-8", "replace") for p in out.split(b"\0") if p]

    try:
        listed = run("-co", "--exclude-standard")
        ignored = run("-o", "-i", "--exclude-standard")
    except (subprocess.SubprocessError, OSError):
        return None
    return sorted(set(listed)), set(ignored)


def _walk_list(root: Path) -> list[str]:
    rels: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for name in filenames:
            full = Path(dirpath) / name
            rels.append(full.relative_to(root).as_posix())
    return sorted(rels)


def _is_sensitive(name: str) -> bool:
    return bool(_SENSITIVE_NAME.match(name)) or Path(name).suffix.lower() in _SENSITIVE_EXT


def _content_skip_reason(path: Path) -> str | None:
    """Skip reason derived from the file's bytes, or None when eligible."""
    try:
        data = path.read_bytes()
    except OSError:
        return "unreadable"
    if b"\0" in data[:8192]:
        return "binary"
    lines = _LINE_SPLIT.split(data.decode("utf-8-sig", errors="replace"))
    if path.name.lower().endswith(".min.js") or any(len(l) > MINIFIED_LINE_CHARS for l in lines):
        return "minified"
    head = "\n".join(lines[:5])
    if any(m in head for m in GENERATED_MARKERS):
        return "generated"
    return None


def inventory(root: Path) -> Inventory:
    root = Path(root)
    if not root.is_dir():
        raise InventoryError("not_a_directory", f"not a directory: {root}")
    root = root.resolve()
    git = _git_lists(root)
    if git is not None:
        rels, ignored = git
        listing = "git"
        rels = sorted(set(rels) | ignored)
    else:
        rels, ignored, listing = _walk_list(root), set(), "walk"
        if shutil.which("git") is not None:
            try:
                res = subprocess.run(
                    ["git", "-C", str(root), "check-ignore", "--stdin", "-z"],
                    input=("\0".join(rels) + "\0").encode(), capture_output=True,
                )
                if res.returncode in (0, 1):
                    ignored = {p.decode("utf-8", "replace") for p in res.stdout.split(b"\0") if p}
            except (subprocess.SubprocessError, OSError):
                pass

    inv = Inventory(root=root, listing=listing)
    for rel in rels:
        path = root / rel
        name = PurePosixPath(rel).name
        parts = PurePosixPath(rel).parts
        if not path.is_file():
            continue
        if _is_sensitive(name):
            inv.skipped.append(Skipped(rel, "sensitive"))
            continue
        if any(p in VENDOR_DIRS for p in parts[:-1]):
            inv.skipped.append(Skipped(rel, "vendored"))
            continue
        if rel in ignored:
            inv.skipped.append(Skipped(rel, "gitignored"))
            continue
        low = name.lower()
        if _LICENSE_NAME.match(name):
            inv.license_files.append(rel)
        if low in _SUPPORTED_MANIFESTS:
            inv.manifests.append(Manifest(rel, _SUPPORTED_MANIFESTS[low]))
        elif re.match(r"^requirements[^/]*\.txt$", low):
            inv.manifests.append(Manifest(rel, "requirements"))
        elif low in _UNSUPPORTED_MANIFESTS:
            inv.manifests.append(Manifest(rel, "unsupported"))
        ext = Path(name).suffix.lower().lstrip(".")
        try:
            size = path.stat().st_size
        except OSError:
            inv.skipped.append(Skipped(rel, "unreadable"))
            continue
        if ext not in LANGUAGES:
            try:
                with open(path, "rb") as fh:
                    binary = b"\0" in fh.read(8192)
            except OSError:
                inv.skipped.append(Skipped(rel, "unreadable"))
                continue
            inv.skipped.append(Skipped(rel, "binary" if binary else "not_source"))
            continue
        if size > MAX_FILE_BYTES:
            inv.skipped.append(Skipped(rel, "too_large"))
            continue
        reason = _content_skip_reason(path)
        if reason:
            inv.skipped.append(Skipped(rel, reason))
            continue
        inv.sources.append(SourceFile(rel, path, LANGUAGES[ext], size))
    if not inv.sources:
        raise InventoryError("no_source_files", f"no source files under {root}")
    return inv


def resolve_includes(inv: Inventory, includes: list[str]) -> list[SourceFile]:
    root = inv.root
    chosen: dict[str, SourceFile] = {}
    for inc in includes:
        norm = inc.replace("\\", "/")
        target = Path(os.path.normpath(root / norm))
        try:
            rel = target.relative_to(root).as_posix()
        except ValueError:
            raise InventoryError("include_outside_root", f"outside root: {inc}") from None
        if not target.exists():
            raise InventoryError("include_not_found", f"not found: {inc}")
        prefix = "" if rel == "." else rel.rstrip("/") + "/"
        found = [s for s in inv.sources if s.rel == rel or s.rel.startswith(prefix)]
        if not found:
            raise InventoryError("include_not_found", f"no source files in: {inc}")
        for s in found:
            chosen[s.rel] = s
    return sorted(chosen.values(), key=lambda s: s.rel)


def main(argv: list[str]) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if len(argv) != 1:
        print(json.dumps({"error": "usage", "message": "inventory.py <root>"}))
        return 2
    try:
        inv = inventory(Path(argv[0]))
    except InventoryError as exc:
        print(json.dumps({"error": exc.code, "message": str(exc)}))
        return 2
    by_dir: dict[str, list[str]] = {}
    for s in inv.sources:
        by_dir.setdefault(str(PurePosixPath(s.rel).parent), []).append(s.rel)
    print(json.dumps({
        "root": str(inv.root),
        "listing": inv.listing,
        "eligible_by_dir": by_dir,
        "skipped": [{"rel": s.rel, "reason": s.reason} for s in inv.skipped],
        "manifests": [{"rel": m.rel, "kind": m.kind} for m in inv.manifests],
        "license_files": inv.license_files,
    }, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
