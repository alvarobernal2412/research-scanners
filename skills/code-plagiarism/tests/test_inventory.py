import hashlib
import json
import shutil
import socket
import subprocess
import sys
from pathlib import Path

import pytest

SKILL = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SKILL / "scripts"))

from inventory import InventoryError, inventory, read_lines, resolve_includes  # noqa: E402


def w(root: Path, rel: str, data=b"x = 1\n"):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data if isinstance(data, bytes) else data.encode())
    return p


def reasons(inv):
    return {s.rel: s.reason for s in inv.skipped}


def test_skips_binary_file(tmp_path):
    w(tmp_path, "ok.py")
    w(tmp_path, "b.py", b"abc\0def\n")
    assert reasons(inventory(tmp_path))["b.py"] == "binary"


def test_skips_huge_file(tmp_path):
    w(tmp_path, "ok.py")
    w(tmp_path, "big.py", b"a = 1\n" * 400_000)
    assert reasons(inventory(tmp_path))["big.py"] == "too_large"


def test_skips_vendored_dirs(tmp_path):
    w(tmp_path, "ok.py")
    w(tmp_path, "node_modules/x.js", "var a = 1;\n")
    assert reasons(inventory(tmp_path))["node_modules/x.js"] == "vendored"


def test_skips_minified_and_generated(tmp_path):
    w(tmp_path, "ok.py")
    w(tmp_path, "a.min.js", "var a=1;\n")
    w(tmp_path, "long.js", "var a = '" + "x" * 600 + "';\n")
    w(tmp_path, "gen.go", "// Code generated by protoc. DO NOT EDIT.\npackage x\n")
    r = reasons(inventory(tmp_path))
    assert r["a.min.js"] == "minified"
    assert r["long.js"] == "minified"
    assert r["gen.go"] == "generated"


def test_sensitive_files_never_eligible(tmp_path):
    w(tmp_path, "ok.py")
    for n in (".env", "id_rsa", "k.pem"):
        w(tmp_path, n, "secret\n")
    inv = inventory(tmp_path)
    r = reasons(inv)
    assert all(r[n] == "sensitive" for n in (".env", "id_rsa", "k.pem"))
    assert [s.rel for s in inv.sources] == ["ok.py"]


def test_no_source_files_raises(tmp_path):
    w(tmp_path, "README.md", "# hi\n")
    w(tmp_path, "a.png", b"\x89PNG\r\n\x1a\n\0\0")
    with pytest.raises(InventoryError) as e:
        inventory(tmp_path)
    assert e.value.code == "no_source_files"


def test_crlf_bom_and_lone_cr_line_numbers(tmp_path):
    p = w(tmp_path, "a.py", b"\xef\xbb\xbfone\r\ntwo\rthree\nfour\n")
    assert read_lines(p) == ["one", "two", "three", "four"]


def test_non_utf8_file_skipped_with_reason(tmp_path):
    w(tmp_path, "ok.py")
    w(tmp_path, "bad.py", "caf\xe9 = 1\n".encode("latin-1"))
    w(tmp_path, "bom.py", b"\xef\xbb\xbfx = 1\n")
    inv = inventory(tmp_path)
    assert reasons(inv)["bad.py"] == "non_utf8"
    assert "bom.py" in [s.rel for s in inv.sources]


def test_read_lines_tolerates_bad_bytes(tmp_path):
    p = w(tmp_path, "a.py", "caf\xe9 = 1\n".encode("latin-1"))
    lines = read_lines(p)
    assert len(lines) == 1 and "caf" in lines[0]


@pytest.mark.parametrize("name", [
    "secrets.py", "credentials_x.py", ".envrc", ".env_local.sh", "id_rsa.bak",
    "secrets.yml", "credentials_prod.json", "Secrets.PY", "a.p12", "a.key", "a.jks"])
def test_sensitive_name_variants(tmp_path, name):
    w(tmp_path, "ok.py")
    w(tmp_path, name, "x = 1\n")
    inv = inventory(tmp_path)
    assert reasons(inv)[name] == "sensitive"
    assert name not in [s.rel for s in inv.sources]


def test_sensitive_does_not_overmatch(tmp_path):
    for n in ("secret_santa.py", "environment.py", "rsa_utils.py", "secrets_docs/readme.md"):
        w(tmp_path, n, "x = 1\n")
    inv = inventory(tmp_path)
    assert {s.rel for s in inv.sources} == {"secret_santa.py", "environment.py", "rsa_utils.py"}
    assert reasons(inv)["secrets_docs/readme.md"] == "not_source"


def test_resolve_includes_backslash_and_outside_root(tmp_path):
    w(tmp_path, "src/lib/a.py")
    w(tmp_path, "other.py")
    inv = inventory(tmp_path)
    assert [s.rel for s in resolve_includes(inv, ["src\\lib"])] == ["src/lib/a.py"]
    with pytest.raises(InventoryError) as e:
        resolve_includes(inv, ["..\\x"])
    assert e.value.code == "include_outside_root"
    with pytest.raises(InventoryError) as e:
        resolve_includes(inv, ["nope"])
    assert e.value.code == "include_not_found"


def test_manifests_detected(tmp_path):
    w(tmp_path, "ok.py")
    for n in ("package.json", "requirements-dev.txt", "pyproject.toml", "go.mod"):
        w(tmp_path, n, "x\n")
    kinds = {m.rel: m.kind for m in inventory(tmp_path).manifests}
    assert kinds == {
        "package.json": "package.json",
        "requirements-dev.txt": "requirements",
        "pyproject.toml": "pyproject",
        "go.mod": "unsupported",
    }


@pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")
def test_gitignored_file_skipped(tmp_path):
    subprocess.run(["git", "init", "-q", str(tmp_path)], check=True)
    w(tmp_path, ".gitignore", "secret.py\n")
    w(tmp_path, "secret.py")
    w(tmp_path, "ok.py")
    inv = inventory(tmp_path)
    assert inv.listing == "git"
    assert reasons(inv)["secret.py"] == "gitignored"
    assert [s.rel for s in inv.sources] == ["ok.py"]


