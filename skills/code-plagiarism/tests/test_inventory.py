def test_cli_not_a_directory_exit_2(tmp_path):
    r = subprocess.run(
        [sys.executable, "-I", str(SKILL / "scripts/inventory.py"), str(tmp_path / "missing")],
        capture_output=True, text=True,
    )
    assert r.returncode == 2
    assert json.loads(r.stdout)["error"] == "not_a_directory"


def test_cli_outputs_listing(tmp_path):
    w(tmp_path, "src/a.py")
    r = subprocess.run(
        [sys.executable, "-I", str(SKILL / "scripts/inventory.py"), str(tmp_path)],
        capture_output=True, text=True,
    )
    assert r.returncode == 0
    assert json.loads(r.stdout)["eligible_by_dir"] == {"src": ["src/a.py"]}


